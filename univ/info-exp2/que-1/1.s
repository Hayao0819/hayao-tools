    # ==========================================
    # メモリマップと役割の定義
    # (1B0H) : 被乗数（足していく数）
    # (180H) : 乗数（足す回数・ループ上限）
    # (182H) : 法（割る数・モジュラス）
    #
    # 処理内容: ACC = ((1B0H) * (180H)) % (182H)
    # ==========================================

    LD      ACC,        0       # ACC（計算結果用レジスタ）を0で初期化
    LD      IX,         0       # IX（ループカウンタ）を0で初期化

MOD_LOOP:
    ADD     ACC,        (1B0H)  # ACCに被乗数(1B0Hの値)を加算する（掛け算の1ステップ）

SUB_LOOP:
    SUB     ACC,        (182H)  # ACCから法(182Hの値)を減算する
    BZP     SUB_LOOP            # 結果が0以上 (Zero or Positive) ならSUB_LOOPへ戻る
    # (マイナスになるまで引き算を繰り返して剰余を求める)

    ADD     ACC,        (182H)  # 引きすぎて負になった分を、法(182H)を足して正の余りに戻す

    ADD     IX,         1       # ループカウンタ(IX)をインクリメント (+1)
    CMP     IX,         (180H)  # カウンタ(IX)と乗数(180Hの値)を比較 (IX - (180H))
    BN      MOD_LOOP            # 結果が負 (Negative) なら (IX < (180H))、MOD_LOOPへ戻る
    # (指定回数に達するまで繰り返す)

    HLT                         # プログラム終了