.data
    .globl  n                   # int n = -128;
n:
    # .word   -128
    .word   128

    .globl  v                   # int v = 0;
v:
    .word   0
.text
    .globl  main
main:
    # ----------------------------------------------------
    # n の値を確認し、n < 0 なら Lp へジャンプ
    # ----------------------------------------------------
    la      $t3,    n           # $t3 = n のアドレス
    lw      $t1,    0($t3)      # $t1 = n (現在の値は -128)
    li      $t2,    0           # $t2 = 0
    sgt     $t0,    $t1,    $t2 # $t0 = 1 if $t1 (n) > 0, else $t0 = 0
    bnez    $t0,    Lp          # if n > 0 (つまり $t0 != 0) then goto Lp (n >= 0 の処理)

    # ----------------------------------------------------
    # n < 0 の場合の処理 (n の絶対値 $|n| = -n$ を計算)
    # ----------------------------------------------------
    # (ここではアドレスを再ロードしているが、前の $t3$ がそのまま使える)
    # la $t2, n    # $t2 = n のアドレス
    # lw $t1, 0($t2) # $t1 = n
    sub     $t0,    $zero,  $t1 # $t0 = -$t1 (-n). ($t1 は n の値)

    la      $t2,    v           # $t2 = v のアドレス
    sw      $t0,    0($t2)      # v = $t0 (-n) 。 (v = |-128| = 128 となる)
    b       Le                  # 処理終了へジャンプ

Lp:
    # ----------------------------------------------------
    # n >= 0 の場合の処理 (n の絶対値 $|n| = n$ を計算)
    # ----------------------------------------------------
    la      $t1,    n           # $t1 = n のアドレス
    lw      $t0,    0($t1)      # $t0 = n

    la      $t1,    v           # $t1 = v のアドレス
    sw      $t0,    0($t1)      # v = $t0 (n)

Le:
    # ----------------------------------------------------
    # プログラム終了
    # ----------------------------------------------------
    li      $v0,    0           # 戻り値 0 を設定 (慣例。ここでは $v0=10$ の syscall でない)
    jr      $ra                 # 呼び出し元へ戻る